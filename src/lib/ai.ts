import OpenAI from "openai";

import { logApiCall } from "~/db";
import type { CreditBureau } from "~/db";

/**
 * Server-only AI engine for ClearScore AI.
 *
 * Three responsibilities:
 *   1. Parse a credit report and surface items the user has a good-faith
 *      basis to dispute.
 *   2. Generate a FCRA-compliant dispute letter addressed to a specific
 *      credit bureau.
 *   3. Estimate the FICO score impact of removing the identified items.
 *
 * Every OpenAI call goes through `complete()` which:
 *   - resolves the API key from `OPENAI_API_KEY`,
 *   - records token usage + estimated cost in `api_logs` for the user,
 *   - throws `AIServiceError` on failure (never a raw OpenAI error).
 *
 * The module is server-only: importing it on the client will fail at the
 * `new OpenAI(...)` call because `OPENAI_API_KEY` is not exposed to the
 * browser. Don't import from a `.tsx` file that's not behind a
 * `createServerFn()`.
 */

// =============================================================================
// Public types — the shapes callers see. Match the JSON the prompts return.
// =============================================================================

export type ErrorCategory =
  | "late_payment"
  | "charge_off"
  | "collection"
  | "repossession"
  | "foreclosure"
  | "bankruptcy"
  | "identity_error"
  | "duplicate_account"
  | "incorrect_balance"
  | "incorrect_status"
  | "outdated_info"
  | "unauthorized_inquiry"
  | "other";

export interface ErrorItem {
  /** Stable id we assign when persisting the item — not generated by the AI. */
  id?: string;
  category: ErrorCategory;
  /** Trade line or item name as it appears on the report, e.g. "CAPITAL ONE". */
  account_name: string;
  /** Last 4 of the account number if available, otherwise null. */
  account_number_last4: string | null;
  bureau: CreditBureau;
  /** One-sentence description of the item, e.g. "30-day late, 03/2024". */
  description: string;
  /** Why we think this is a valid dispute candidate. */
  reason: string;
  /** 0-1, the model's confidence the item is actually inaccurate. */
  confidence: number;
}

export interface AnalysisResult {
  bureau: CreditBureau | "all";
  errors: ErrorItem[];
  /** Short summary the dashboard can show above the list. */
  summary: string;
  /** Tokens the AI used for this call. Useful for displaying to the user. */
  tokens_used: number;
}

export interface ScoreImpactEstimate {
  /** Estimated total point gain if all listed items are removed. */
  estimated_point_gain_low: number;
  estimated_point_gain_mid: number;
  estimated_point_gain_high: number;
  /** Per-item contribution, same indexes as the input array. */
  per_item: Array<{
    category: ErrorCategory;
    impact_low: number;
    impact_mid: number;
    impact_high: number;
    rationale: string;
  }>;
  /** Caveats the user should know — recovery isn't guaranteed. */
  caveats: string[];
  tokens_used: number;
}

// =============================================================================
// Errors
// =============================================================================

export class AIServiceError extends Error {
  constructor(
    message: string,
    public readonly code:
      | "missing_api_key"
      | "openai_error"
      | "invalid_response"
      | "rate_limited"
      | "schema_validation",
    public readonly cause?: unknown,
  ) {
    super(message);
    this.name = "AIServiceError";
  }
}

// =============================================================================
// Client + config
// =============================================================================

const DEFAULT_MODEL = "gpt-4o-mini";
/** Used for the dispute letter where prose quality matters most. */
const PREMIUM_MODEL = "gpt-4o";

/** Per-1K-token prices (USD) — keep in sync with OpenAI's pricing page. */
const PRICES: Record<string, { input: number; output: number }> = {
  "gpt-4o-mini": { input: 0.00015, output: 0.0006 },
  "gpt-4o": { input: 0.005, output: 0.015 },
};

let _client: OpenAI | null = null;
const getClient = (): OpenAI => {
  if (_client) return _client;
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    throw new AIServiceError(
      "OPENAI_API_KEY is not set — connect the OpenAI integration (via the spend request) before calling the AI engine.",
      "missing_api_key",
    );
  }
  _client = new OpenAI({ apiKey });
  return _client;
};

const estimateCost = (
  model: string,
  prompt_tokens: number,
  completion_tokens: number,
): number => {
  const p = PRICES[model] ?? PRICES[DEFAULT_MODEL];
  return (prompt_tokens / 1000) * p.input + (completion_tokens / 1000) * p.output;
};

// =============================================================================
// Core: one place every OpenAI call goes through.
// =============================================================================

interface CompleteArgs {
  endpoint: string;
  user_id?: string | null;
  model?: string;
  system: string;
  user: string;
  /** Required `response_format: { type: "json_object" }` for typed parsing. */
  json: true;
  /** Sampling temperature. Default low for predictable JSON. */
  temperature?: number;
}

const complete = async <T>(args: CompleteArgs): Promise<T> => {
  const model = args.model ?? DEFAULT_MODEL;
  try {
    const completion = await getClient().chat.completions.create({
      model,
      temperature: args.temperature ?? 0.2,
      response_format: { type: "json_object" },
      messages: [
        { role: "system", content: args.system },
        { role: "user", content: args.user },
      ],
    });

    const message = completion.choices[0]?.message?.content;
    if (!message) {
      throw new AIServiceError(
        "OpenAI returned an empty completion",
        "invalid_response",
      );
    }

    const usage = completion.usage;
    const prompt_tokens = usage?.prompt_tokens ?? 0;
    const completion_tokens = usage?.completion_tokens ?? 0;
    const tokens_used = prompt_tokens + completion_tokens;
    const cost = estimateCost(model, prompt_tokens, completion_tokens);

    // Fire-and-forget logging — don't block the response on a DB write, but
    // surface any error to stderr so the server log captures it.
    logApiCall({
      user_id: args.user_id ?? null,
      endpoint: args.endpoint,
      model,
      tokens_used,
      cost,
      meta: {
        prompt_tokens,
        completion_tokens,
        temperature: args.temperature ?? 0.2,
      },
    }).catch((err) => {
      console.error("[ai] logApiCall failed:", err);
    });

    try {
      return JSON.parse(message) as T;
    } catch (err) {
      throw new AIServiceError(
        "OpenAI returned a response that wasn't valid JSON",
        "schema_validation",
        err,
      );
    }
  } catch (err) {
    if (err instanceof AIServiceError) throw err;
    const message = err instanceof Error ? err.message : String(err);
    // OpenAI surfaces 429 with status code; map it to a friendlier code.
    if (message.includes("429") || message.toLowerCase().includes("rate")) {
      throw new AIServiceError(message, "rate_limited", err);
    }
    throw new AIServiceError(message, "openai_error", err);
  }
};

