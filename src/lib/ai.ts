/**
 * Analyze a parsed credit report and surface dispute candidates.
 *
 * @param reportText  The parsed report as plain text. Keep the structure the
 *                    parser produced (account blocks, balances, statuses) —
 *                    the model uses the layout to ground its reasoning.
 * @param bureau      Which bureau this report came from, or "all" if the
 *                    report is a combined view.
 * @param user_id     Optional — when provided, the call is recorded against
 *                    the user in `api_logs` for cost / usage tracking.
 */
export const analyzeCreditReport = async (
  reportText: string,
  bureau: CreditBureau | "all" = "all",
  user_id?: string,
): Promise<AnalysisResult> => {
  if (!reportText || reportText.trim().length < 50) {
    throw new AIServiceError(
      "Report text is too short to analyze — need at least 50 characters of parsed content.",
      "schema_validation",
    );
  }

  type Raw = { summary: string; errors: Omit<ErrorItem, "id">[] };
  const result = await complete<Raw>({
    endpoint: "analyzeCreditReport",
    user_id,
    system: SYSTEM_ANALYZER,
    user: `Bureau: ${bureau}\n\n--- CREDIT REPORT ---\n${reportText}`,
    json: true,
  });

  // Normalize + validate the AI's output before returning — a confident model
  // can still produce a category we don't know about, or a bureau we don't
  // support. Drop bad rows rather than rejecting the whole response.
  const knownCategories: ReadonlySet<ErrorCategory> = new Set([
    "late_payment",
    "charge_off",
    "collection",
    "repossession",
    "foreclosure",
    "bankruptcy",
    "identity_error",
    "duplicate_account",
    "incorrect_balance",
    "incorrect_status",
    "outdated_info",
    "unauthorized_inquiry",
    "other",
  ]);
  const knownBureaus: ReadonlySet<string> = new Set([
    "equifax",
    "experian",
    "transunion",
  ]);

  const errors: ErrorItem[] = (result.errors ?? [])
    .filter((e) => e && typeof e === "object")
    .map((e) => ({
      ...e,
      category: knownCategories.has(e.category as ErrorCategory)
        ? (e.category as ErrorCategory)
        : "other",
      // If the AI said "all" or a bureau we don't support, fall back to the
      // bureau the user is currently viewing the report from.
      bureau: knownBureaus.has(e.bureau)
        ? (e.bureau as CreditBureau)
        : bureau === "all"
          ? "equifax"
          : bureau,
      confidence:
        typeof e.confidence === "number"
          ? Math.max(0, Math.min(1, e.confidence))
          : 0.5,
      account_number_last4: e.account_number_last4 ?? null,
    }));

  return {
    bureau,
    summary: result.summary ?? "",
    errors,
    tokens_used: 0, // logged separately; the public type is for the UI
  };
};

/**
 * Generate a FCRA-compliant dispute letter for a single error item.
 *
 * @param error   The dispute candidate from `analyzeCreditReport`.
 * @param bureau  Which bureau the letter is addressed to. Must be one of
 *                equifax / experian / transunion — "all" doesn't make sense
 *                for a single letter.
 * @param consumer  Identifying info that has to appear in the letter.
 * @param user_id   Optional — recorded in `api_logs`.
 */
export const generateDisputeLetter = async (
  error: ErrorItem,
  bureau: CreditBureau,
  consumer: {
    full_name: string;
    current_address: string;
    ssn_last4: string;
    date_of_birth: string; // YYYY-MM-DD
  },
  user_id?: string,
): Promise<{ letter: string; key_facts: string[]; tokens_used: number }> => {
  if (bureau === ("all" as unknown as CreditBureau)) {
    throw new AIServiceError(
      "generateDisputeLetter needs a single bureau — got 'all'",
      "schema_validation",
    );
  }

  type Raw = { letter: string; key_facts: string[] };
  const result = await complete<Raw>({
    endpoint: "generateDisputeLetter",
    user_id,
    model: PREMIUM_MODEL, // letter quality > cost
    system: SYSTEM_LETTER_WRITER,
    user: `Bureau: ${bureau}

Consumer:
- Name: ${consumer.full_name}
- Address: ${consumer.current_address}
- SSN (last 4): ${consumer.ssn_last4}
- DOB: ${consumer.date_of_birth}

Disputed item:
- Category: ${error.category}
- Account: ${error.account_name}${error.account_number_last4 ? ` (…${error.account_number_last4})` : ""}
- Description: ${error.description}
- Reason for dispute: ${error.reason}`,
    json: true,
  });

  return {
    letter: result.letter ?? "",
    key_facts: Array.isArray(result.key_facts) ? result.key_facts : [],
    tokens_used: 0,
  };
};

/**
 * Estimate the FICO score impact of removing the given items.
 *
 * @param errors   The items from `analyzeCreditReport` the user wants to act on.
 * @param user_id  Optional — recorded in `api_logs`.
 */
export const estimateScoreImpact = async (
  errors: ErrorItem[],
  user_id?: string,
): Promise<ScoreImpactEstimate> => {
  if (errors.length === 0) {
    return {
      estimated_point_gain_low: 0,
      estimated_point_gain_mid: 0,
      estimated_point_gain_high: 0,
      per_item: [],
      caveats: ["No items to estimate — add at least one dispute candidate."],
      tokens_used: 0,
    };
  }

  type Raw = Omit<ScoreImpactEstimate, "tokens_used">;
  const result = await complete<Raw>({
    endpoint: "estimateScoreImpact",
    user_id,
    system: SYSTEM_SCORER,
    user: `Estimate FICO point impact if these items are successfully removed:\n\n${JSON.stringify(errors, null, 2)}`,
    json: true,
  });

  return {
    estimated_point_gain_low: Math.max(0, Math.round(result.estimated_point_gain_low ?? 0)),
    estimated_point_gain_mid: Math.max(0, Math.round(result.estimated_point_gain_mid ?? 0)),
    estimated_point_gain_high: Math.max(0, Math.round(result.estimated_point_gain_high ?? 0)),
    per_item: Array.isArray(result.per_item)
      ? result.per_item.map((p) => ({
          category: (p.category as ErrorCategory) ?? "other",
          impact_low: Math.max(0, Math.round(p.impact_low ?? 0)),
          impact_mid: Math.max(0, Math.round(p.impact_mid ?? 0)),
          impact_high: Math.max(0, Math.round(p.impact_high ?? 0)),
          rationale: p.rationale ?? "",
        }))
      : [],
    caveats: Array.isArray(result.caveats) ? result.caveats : [],
    tokens_used: 0,
  };
};

